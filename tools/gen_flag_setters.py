#!/usr/bin/env python3
"""Writes games/acnl/src/core/flag_setters.cpp: every not yet rewritten function of the game that is a one-bit flag
setter on a byte of its object (`cmp r1, #0; ldrb; orrne; biceq; strb; bx lr`, possibly behind a branch thunk).

    tools/gen_flag_setters.py

The functions are found by their instruction pattern, so running it again after more rewrites only emits what is
still left (the file lists every address it exports, regenerate it before committing changes to the pattern).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'harness'))
import fn as fnmod  # noqa: E402
import harness as h  # noqa: E402
from program import Program  # noqa: E402

FLAG = re.compile(r'^cmp r1, #0\nldrb r1, \[r0(?:, #(0x[0-9a-f]+|\d+))?\]\norrne r1, r1, #(0x[0-9a-f]+|\d+)\n'
                  r'biceq r1, r1, #(0x[0-9a-f]+|\d+)\nstrb r1, \[r0(?:, #(0x[0-9a-f]+|\d+))?\]\nbx lr$')
OUT = os.path.join(ROOT, 'games', 'acnl', 'src', 'core', 'flag_setters.cpp')


def find_setters(p, state):
    found = []
    for key, f in p.funcs.items():
        status = state.data['functions'].get('%x' % key, {}).get('status')
        if key in p.rewritten and p.rewritten[key] != 'games/acnl/src/core/flag_setters.cpp':
            continue
        if status == 'skipped' or not f.callers or f.ninsts > 14 or f.svcs or p.callees(key) or f.icalls:
            continue
        lines = [l for l in fnmod.disasm(p, key).split('\n') if not re.match(r'^L_[0-9a-f]+:', l)]
        body = '\n'.join(' '.join(re.sub(r';.*$', '', re.sub(r'^\s+[0-9a-f]{8}\s+', '', l)).split()) for l in lines)
        body = re.sub(r'^b L_[0-9a-f]+\n', '', body)
        m = FLAG.match(body)
        if m and m.group(2) == m.group(3) and (m.group(1) or '0') == (m.group(4) or '0'):
            found.append((key, int(m.group(1) or '0', 0), int(m.group(2), 0)))
    return sorted(found)


def main():
    p = Program('acnl')
    state = h.State()
    found = find_setters(p, state)
    offsets = sorted(set(o for _, o, _ in found))
    masks = sorted(set(m for _, _, m in found))
    out = ['''// Setters of one bit (a flag) of a byte of an object: the bit is set when the flag argument is non-zero and cleared
// when it is zero. They belong to packed records whose layout is not known yet, so the functions are named after
// the byte and bit they change. Generated by tools/gen_flag_setters.py from the instruction pattern.
#include "guest/guest.hpp"

using guest::gptr;

namespace {
''']
    for o in offsets:
        out.append('constexpr u32 BYTE_%02X = 0x%02x;' % (o, o))
    out.append('')
    for m in masks:
        out.append('constexpr u8 MASK_%02X = 0x%02x;' % (m, m))
    out.append('''
constexpr u32 FUZZ_OBJECT_SIZE = 0x800;

void assign_bit(gptr<u8> object, u32 byte, u8 mask, u32 on) {
    if (on != 0) {
        object[byte] = object[byte] | mask;
    } else {
        object[byte] = object[byte] & ~mask;
    }
}

void fuzz_flag_setter(guest::Fuzz &f) {
    auto object = f.allocate(FUZZ_OBJECT_SIZE).cast<u8>();
    f.bytes(object, FUZZ_OBJECT_SIZE);
    f.arguments(object, f.pick<u32>({0, 1, 0x100, f.number()}));
}

}  // namespace
''')
    for key, offset, mask in found:
        bit = mask.bit_length() - 1
        name = 'assign_bit%d_of_byte%02x_%x' % (bit, offset, key)
        out.append('void %s(gptr<u8> object, u32 on) { assign_bit(object, BYTE_%02X, MASK_%02X, on); }' % (name, offset, mask))
        out.append('GUEST_EXPORT(0x%08x, %s);' % (key, name))
        out.append('GUEST_FUZZ(0x%08x, 100, [](guest::Fuzz &f) { fuzz_flag_setter(f); });' % (key, ))
        out.append('')
    with open(OUT, 'w') as f:
        f.write('\n'.join(out))
    print('%d flag setters -> %s' % (len(found), OUT))


if __name__ == '__main__':
    main()
