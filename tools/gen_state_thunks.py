#!/usr/bin/env python3
"""Writes games/acnl/src/core/state_thunks.cpp: the thunks that store a new state in their object and then call
the member function the state selects in a table of pointers to member functions (16 bytes per state):

    ldr r3, [pc]; ldr r2, [pc]; str r1, [r3, r0]; add r1, r2, r1, lsl #4; ldr r2, [r1, #4]; tst r2, #1; ...

Found by their instruction pattern; run it again after more rewrites to emit what is left.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'harness'))
import fn as fnmod  # noqa: E402
import harness as h  # noqa: E402
from program import Program  # noqa: E402

OUT = os.path.join(ROOT, 'games', 'acnl', 'src', 'core', 'state_thunks.cpp')
THIS = 'games/acnl/src/core/state_thunks.cpp'
PATTERN = ['ldr r3, [pc, #N]', 'ldr r2, [pc, #N]', 'str r1, [r3, r0]', 'add r1, r2, r1, lsl #4', 'ldr r2, [r1, #4]',
           'tst r2, #1', 'ldreq r1, [r1]', 'add r0, r0, r2, asr #1', 'beq L', 'ldr r2, [r0]', 'ldr r1, [r1]',
           'ldr r1, [r2, r1]', 'nop', 'bx r1']


def normalise(line):
    line = ' '.join(re.sub(r';.*$', '', re.sub(r'^\s+[0-9a-f]{8}\s+', '', line)).split())
    line = re.sub(r'beq L_[0-9a-f]+', 'beq L', line)
    return re.sub(r'#0x[0-9a-f]+|#\d+', lambda m: m.group(0) if m.group(0) in ('#1', '#4') else '#N', line)


def main():
    p = Program('acnl')
    state = h.State()
    found = []
    for key, f in sorted(p.funcs.items()):
        status = state.data['functions'].get('%x' % key, {}).get('status')
        if f.thumb or status == 'skipped' or f.ninsts != 14 or not f.callers:
            continue
        if key in p.rewritten and p.rewritten[key] != THIS:
            continue
        lines = [l for l in fnmod.disasm(p, key).split('\n') if not re.match(r'^L_[0-9a-f]+:', l)]
        if [normalise(l) for l in lines] != PATTERN:
            continue
        lits = dict(f.lits)
        addrs = [a for a, _ in f.insts]
        table_pool = None
        if key >= 0x40000000:  # the table is data of the CRO module: its address comes from the relocated literal
            m = re.search(r'\[pc, #(0x[0-9a-f]+|\d+)\]', lines[1])
            table_pool = addrs[1] + 8 + int(m.group(1), 0)
        found.append((key, lits[addrs[0]], lits[addrs[1]], table_pool))
    out = ['''// Thunks that store a new state in a word of their object and call the member function the state selects in a table
// (16 bytes per state: the function and the this-adjustment, as the ARM C++ ABI stores a pointer to member function).
// The classes are the NPC and menu classes that switch states through such tables. Generated by
// tools/gen_state_thunks.py from the instruction pattern.
#include "core/fuzz_helpers.hpp"
#include "guest/guest.hpp"

using guest::gptr;

namespace {

constexpr u32 FUZZ_STATES = 8;
constexpr u32 FUZZ_OBJECT_SIZE = 0x4000;

// An entry of the table: the handler, then eight bytes whose meaning is not known yet (probably its name).
struct StateEntry {
    guest::MemberFunctionPointer handler;
    u32 unknown_08[2];
};
GUEST_SIZE(StateEntry, 16);

// Stores the state at the offset of the object, then calls the state's handler on the object.
u32 enter_state(gptr<u8> object, u32 state_offset, u32 table, u32 state) {
    *gptr<u32>(object.addr() + state_offset) = state;
    const StateEntry &entry = gptr<StateEntry>(table)[state];
    return guest::call_member<u32>(entry.handler, object);
}

// Points the first states of the table at a harmless function (the real handlers are game code that needs a real
// object), then calls the thunk with a state among them.
void fuzz_thunk(guest::Fuzz &f, u32 table, u32 state_offset) {
    gptr<StateEntry> entries(table);
    for (u32 i = 0; i < FUZZ_STATES; i++) {
        entries[i].handler.function = fuzz::ENCRYPTED_INT_GET;
        entries[i].handler.adjust = 0;
    }
    auto object = f.allocate(FUZZ_OBJECT_SIZE).cast<u8>();
    f.bytes(object, state_offset + 8);
    f.arguments(object, f.below(FUZZ_STATES));
}

}  // namespace
''']
    for key, offset, table, pool in found:
        name = 'enter_state_%x' % key
        if pool is None:
            table_expr = '0x%08x' % table
        else:
            table_expr = 'guest::relocated_global<u8, 0x%08x>::address()' % pool
        out.append('u32 %s(gptr<u8> object, u32 state) { return enter_state(object, 0x%x, %s, state); }' % (name, offset, table_expr))
        out.append('GUEST_EXPORT(0x%08x, %s);' % (key, name))
        out.append('GUEST_FUZZ(0x%08x, 100, [](guest::Fuzz &f) { fuzz_thunk(f, %s, 0x%x); });' % (key, table_expr, offset))
        out.append('')
    with open(OUT, 'w') as f:
        f.write('\n'.join(out))
    print(len(found), 'state thunks ->', OUT)


if __name__ == '__main__':
    main()
